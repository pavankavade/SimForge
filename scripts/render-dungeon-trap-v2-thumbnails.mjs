/**
 * Renders every DungeonTrapV2 shorts thumbnail variant to out/thumbnails/.
 * Each variant's frame comes from the composition's calculateMetadata
 * (derived from BEATS), so re-voicing the episode never stales a thumbnail.
 * Bundles only the thumbnail (like scripts/solo.mjs), so a half-built episode
 * elsewhere in src/Root.tsx cannot break it.
 *
 *   npm run thumb:dungeon-trap-v2
 */
import { bundle } from "@remotion/bundler";
import { renderStill, selectComposition } from "@remotion/renderer";
import path from "node:path";
import fs from "node:fs";

const root = path.resolve(import.meta.dirname, "..");
const ID = "DungeonTrapV2Thumbnail";
const outDir = path.join(root, "out", "thumbnails");
fs.mkdirSync(outDir, { recursive: true });
const tmp = path.join(root, "out", "tmp");
fs.mkdirSync(tmp, { recursive: true });
process.env.TEMP = process.env.TMP = process.env.TMPDIR = tmp;

const soloDir = path.join(root, "out", "solo");
fs.mkdirSync(soloDir, { recursive: true });
const entry = path.join(soloDir, `${ID}.js`);
fs.writeFileSync(
  entry,
  `// Generated by scripts/render-dungeon-trap-v2-thumbnails.mjs.
import React from "react";
import { Composition, registerRoot } from "remotion";
import { DungeonTrapV2Thumbnail, dungeonV2ThumbMetadata } from "../../src/episodes/dungeon-trap-v2/Thumbnail";
import { DURATION } from "../../src/episodes/dungeon-trap-v2/timeline";

registerRoot(() =>
  React.createElement(Composition, {
    id: "${ID}",
    component: DungeonTrapV2Thumbnail,
    durationInFrames: DURATION,
    fps: 30,
    width: 1080,
    height: 1920,
    defaultProps: { variant: 0 },
    calculateMetadata: dungeonV2ThumbMetadata,
  })
);
`
);

console.log("Bundling...");
const serveUrl = await bundle({ entryPoint: entry, rspack: true, enableCaching: false });

const chromiumOptions = { gl: "angle" };
const first = await selectComposition({ serveUrl, id: ID, inputProps: { variant: 0 }, chromiumOptions });
const count = first.props.count ?? 1;
for (let i = 0; i < count; i++) {
  const inputProps = { variant: i };
  const composition = i === 0 ? first : await selectComposition({ serveUrl, id: ID, inputProps, chromiumOptions });
  const output = path.join(outDir, `dungeon-trap-v2-thumb-${i + 1}.png`);
  await renderStill({ serveUrl, composition, frame: composition.props.frame, output, inputProps, chromiumOptions });
  console.log(`variant ${i + 1} (frame ${composition.props.frame}) -> ${output}`);
}
