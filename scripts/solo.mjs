#!/usr/bin/env node
/**
 * Renders one episode without bundling the whole studio.
 *
 *   node scripts/solo.mjs render <CompositionId> [remotion render args...]
 *   node scripts/solo.mjs still  <CompositionId> [remotion still args...]
 *   node scripts/solo.mjs entry  <CompositionId>      # print the entry path
 *
 * `remotion render <Id>` bundles src/index.ts -> src/Root.tsx, which imports
 * every episode, so one half-built episode anywhere (a missing file, a bad
 * import) breaks every render. This writes a tiny entry that imports only the
 * episode whose config.ts has `id: "<CompositionId>"` and passes it to the
 * remotion CLI. Compositions that are not a defineEpisode() episode
 * (thumbnails, the campaign, the lab) fall back to the full src/index.ts.
 *
 * The entry is plain JS in out/solo/ (gitignored, outside eslint/tsc).
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SERIES_DIRS = ["src/episodes", "src/shelter", "src/whatif"];
export const FULL_ENTRY = path.join(root, "src", "index.ts");

/** The episode folder whose config.ts declares this composition id, or null. */
export const findEpisodeDir = (id) => {
  const decl = new RegExp(`\\bid:\\s*["'\`]${id}["'\`]`);
  for (const series of SERIES_DIRS) {
    const dir = path.join(root, series);
    if (!fs.existsSync(dir)) continue;
    for (const name of fs.readdirSync(dir)) {
      const ep = path.join(dir, name);
      const config = path.join(ep, "config.ts");
      if (fs.existsSync(config) && fs.existsSync(path.join(ep, "index.ts")) && decl.test(fs.readFileSync(config, "utf8"))) return ep;
    }
  }
  return null;
};

/** Writes out/solo/<Id>.js for an episode and returns its path (null if `id` is not an episode). */
export const soloEntry = (id) => {
  const ep = findEpisodeDir(id);
  if (!ep) return null;
  const outDir = path.join(root, "out", "solo");
  fs.mkdirSync(outDir, { recursive: true });
  const file = path.join(outDir, `${id}.js`);
  const rel = path.relative(outDir, path.join(ep, "index")).split(path.sep).join("/");
  fs.writeFileSync(
    file,
    `// Generated by scripts/solo.mjs: ${id} on its own, without src/Root.tsx.
import React from "react";
import { Composition, registerRoot } from "remotion";
import * as mod from "${rel}";

const ep = Object.keys(mod)
  .map((k) => mod[k])
  .find((e) => e && e.Video && e.config && e.config.id === "${id}");
if (!ep) throw new Error("${rel} exports no episode with id ${id}");
const c = ep.config;

registerRoot(() =>
  React.createElement(Composition, {
    id: c.id,
    component: ep.Video,
    durationInFrames: c.durationInFrames,
    fps: c.fps,
    width: c.width,
    height: c.height,
    defaultProps: { beats: ep.beats, audit: ep.audit },
  })
);
`
  );
  return file;
};

/** Solo entry for `id` if it is an episode, else the full studio entry. */
export const entryFor = (id) => soloEntry(id) ?? FULL_ENTRY;

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [cmd, id, ...rest] = process.argv.slice(2);
  if (!["render", "still", "entry"].includes(cmd) || !id) {
    console.error("usage: node scripts/solo.mjs <render|still|entry> <CompositionId> [remotion args...]");
    process.exit(1);
  }
  const entry = entryFor(id);
  if (cmd === "entry") {
    console.log(entry);
    process.exit(0);
  }
  console.log(entry === FULL_ENTRY ? `${id}: not a standalone episode, bundling the full studio` : `${id}: solo entry ${path.relative(root, entry)}`);
  const cli = path.join(root, "node_modules", "@remotion", "cli", "remotion-cli.js");
  // Frames, downloaded assets and Chrome profiles go to the OS temp dir; keep them on the repo's
  // drive (out/tmp) so a full system drive cannot starve the render.
  const tmp = path.join(root, "out", "tmp");
  fs.mkdirSync(tmp, { recursive: true });
  const env = { ...process.env, TEMP: tmp, TMP: tmp, TMPDIR: tmp };
  const res = spawnSync(process.execPath, [cli, cmd, entry, id, ...rest], { cwd: root, stdio: "inherit", env });
  process.exit(res.status ?? 1);
}
